
from pathlib import Path

import cv2
import joblib
import librosa
import numpy as np
import tensorflow as tf


# =========================================================
# PATHS AND SETTINGS
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

IMAGE_MODEL_PATH = BASE_DIR / "models" / "image_model.keras"
AUDIO_MODEL_PATH = BASE_DIR / "models" / "audio_model.joblib"
VIDEO_MODEL_PATH = BASE_DIR / "models" / "video_model.joblib"

IMAGE_SIZE = (224, 224)
FRAMES_PER_VIDEO = 12

AUDIO_SAMPLE_RATE = 16000
AUDIO_MAX_SECONDS = 10
AUDIO_N_MFCC = 20

# Set according to the labels used when training image_model.keras.
# True  = sigmoid output represents REAL probability.
# False = sigmoid output represents FAKE probability.
OUTPUT_IS_REAL_PROBABILITY = True

_image_model = None
_audio_package = None
_video_package = None


# =========================================================
# LOAD MODELS
# =========================================================

def get_image_model():
    global _image_model

    if _image_model is None:
        if not IMAGE_MODEL_PATH.exists():
            raise FileNotFoundError(
                f"Image model not found: {IMAGE_MODEL_PATH}"
            )

        _image_model = tf.keras.models.load_model(
            IMAGE_MODEL_PATH,
            compile=False
        )

        print("DeepGuard X image model loaded.")
        print("Image input:", _image_model.input_shape)
        print("Image output:", _image_model.output_shape)

    return _image_model


def get_audio_package():
    global _audio_package

    if _audio_package is None:
        if not AUDIO_MODEL_PATH.exists():
            raise FileNotFoundError(
                f"Audio model not found: {AUDIO_MODEL_PATH}"
            )

        package = joblib.load(AUDIO_MODEL_PATH)

        if not isinstance(package, dict) or "model" not in package:
            raise ValueError(
                "Audio model package is invalid. "
                "Check the output of train_audio.py."
            )

        _audio_package = package

    return _audio_package


def get_video_package():
    global _video_package

    if _video_package is None:
        if not VIDEO_MODEL_PATH.exists():
            raise FileNotFoundError(
                f"Video model not found: {VIDEO_MODEL_PATH}. "
                "Run train_video.py successfully first."
            )

        package = joblib.load(VIDEO_MODEL_PATH)

        if not isinstance(package, dict) or "model" not in package:
            raise ValueError(
                "Video model package is invalid. "
                "Check the output of train_video.py."
            )

        _video_package = package

    return _video_package


# =========================================================
# IMAGE ANALYSIS
# =========================================================

def analyze_image(file_path):
    model = get_image_model()

    image = tf.keras.utils.load_img(
        str(file_path),
        target_size=IMAGE_SIZE,
        color_mode="rgb"
    )

    image = tf.keras.utils.img_to_array(image)
    image = np.expand_dims(image, axis=0)

    # Must match the preprocessing used during image training.
    # Standard EfficientNetB0 with built-in preprocessing
    # commonly expects pixel values in the 0-255 range.
    output = model.predict(image, verbose=0)
    probability = float(np.asarray(output).reshape(-1)[0])

    if not np.isfinite(probability) or not 0 <= probability <= 1:
        raise ValueError(
            f"Invalid image model probability: {probability}"
        )

    if OUTPUT_IS_REAL_PROBABILITY:
        real_probability = probability
        fake_probability = 1.0 - probability
    else:
        fake_probability = probability
        real_probability = 1.0 - probability

    prediction = "Real" if real_probability >= 0.5 else "Fake"

    return {
        "status": "complete",
        "prediction": prediction,
        "label": f"Prediction: {prediction}",
        "confidence": round(
            max(real_probability, fake_probability) * 100, 2
        ),
        "real_probability": round(real_probability * 100, 2),
        "fake_probability": round(fake_probability * 100, 2),
        "media_type": "image",
        "explanation": "Prediction generated by the trained image classifier.",
        "disclaimer": (
            "This model's estimate is not proof of authenticity."
        )
    }


# =========================================================
# AUDIO FEATURE EXTRACTION
# =========================================================

def extract_audio_features(file_path, package):
    sample_rate = int(
        package.get("sample_rate", AUDIO_SAMPLE_RATE)
    )
    max_seconds = float(
        package.get("max_seconds", AUDIO_MAX_SECONDS)
    )
    n_mfcc = int(
        package.get("n_mfcc", AUDIO_N_MFCC)
    )

    audio, _ = librosa.load(
        str(file_path),
        sr=sample_rate,
        mono=True,
        duration=max_seconds
    )

    if audio.size == 0:
        raise ValueError("The audio file is empty or unreadable.")

    mfcc = librosa.feature.mfcc(
        y=audio,
        sr=sample_rate,
        n_mfcc=n_mfcc,
        n_fft=512,
        hop_length=160
    )

    # Must match train_audio.py: MFCC means followed by standard deviations.
    features = np.concatenate([
        np.mean(mfcc, axis=1),
        np.std(mfcc, axis=1)
    ]).reshape(1, -1)

    expected_features = int(
        package.get("feature_count", 2 * n_mfcc)
    )

    if features.shape[1] != expected_features:
        raise ValueError(
            f"Audio feature mismatch: extracted {features.shape[1]} "
            f"features, but the model expects {expected_features}."
        )

    return features


# =========================================================
# AUDIO ANALYSIS
# =========================================================

def analyze_audio(file_path):
    package = get_audio_package()
    model = package["model"]

    features = extract_audio_features(file_path, package)

    predicted_value = int(model.predict(features)[0])

    label_mapping = package.get(
        "label_mapping",
        {0: "real", 1: "fake"}
    )

    prediction = str(
        label_mapping.get(predicted_value, predicted_value)
    ).capitalize()

    real_probability = None
    fake_probability = None

    if hasattr(model, "predict_proba"):
        probabilities = model.predict_proba(features)[0]
        classes = list(model.classes_)

        if 0 in classes:
            real_probability = float(
                probabilities[classes.index(0)] * 100
            )

        if 1 in classes:
            fake_probability = float(
                probabilities[classes.index(1)] * 100
            )

    confidence = None

    if real_probability is not None and fake_probability is not None:
        confidence = max(real_probability, fake_probability)

    return {
        "status": "complete",
        "prediction": prediction,
        "label": f"Audio prediction: {prediction}",
        "confidence": (
            round(confidence, 2) if confidence is not None else None
        ),
        "real_probability": (
            round(real_probability, 2)
            if real_probability is not None else None
        ),
        "fake_probability": (
            round(fake_probability, 2)
            if fake_probability is not None else None
        ),
        "media_type": "audio",
        "explanation": (
            "Prediction generated from MFCC features and the trained "
            "audio classifier."
        ),
        "disclaimer": (
            "This is a model estimate, not proof that the audio is genuine "
            "or manipulated."
        )
    }


# =========================================================
# VIDEO ANALYSIS
# =========================================================

def analyze_video(file_path):
    package = get_video_package()
    video_model = package["model"]
    image_model = get_image_model()

    frame_count = int(
        package.get("frames_per_video", FRAMES_PER_VIDEO)
    )
    image_size = tuple(
        package.get("image_size", IMAGE_SIZE)
    )

    cap = cv2.VideoCapture(str(file_path))

    if not cap.isOpened():
        raise ValueError("Could not open the uploaded video.")

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    if total_frames <= 0:
        cap.release()
        raise ValueError("The video contains no readable frames.")

    positions = np.linspace(
        0,
        total_frames - 1,
        min(frame_count, total_frames),
        dtype=int
    )

    frames = []

    for position in positions:
        cap.set(cv2.CAP_PROP_POS_FRAMES, int(position))
        success, frame = cap.read()

        if not success:
            continue

        frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        frame = cv2.resize(frame, image_size)
        frames.append(frame)

    cap.release()

    if not frames:
        raise ValueError("Could not extract frames from the video.")

    batch = np.asarray(frames, dtype=np.float32)

    # Match the preprocessing used to train image_model.keras.
    # If image training used rescale=1./255, uncomment:
    # batch = batch / 255.0

    frame_scores = image_model.predict(
        batch,
        verbose=0
    ).reshape(-1)

    # These eight features must match train_video.py exactly.
    features = np.array([[
        np.mean(frame_scores),
        np.std(frame_scores),
        np.min(frame_scores),
        np.max(frame_scores),
        np.median(frame_scores),
        np.percentile(frame_scores, 25),
        np.percentile(frame_scores, 75),
        len(frame_scores) / frame_count
    ]], dtype=np.float32)

    predicted_value = int(video_model.predict(features)[0])
    prediction = "Fake" if predicted_value == 1 else "Real"

    real_probability = None
    fake_probability = None

    if hasattr(video_model, "predict_proba"):
        probabilities = video_model.predict_proba(features)[0]
        classes = list(video_model.classes_)

        if 0 in classes:
            real_probability = float(
                probabilities[classes.index(0)] * 100
            )

        if 1 in classes:
            fake_probability = float(
                probabilities[classes.index(1)] * 100
            )

    confidence = None

    if real_probability is not None and fake_probability is not None:
        confidence = max(real_probability, fake_probability)

    return {
        "status": "complete",
        "prediction": prediction,
        "label": f"Video prediction: {prediction}",
        "confidence": (
            round(confidence, 2) if confidence is not None else None
        ),
        "real_probability": (
            round(real_probability, 2)
            if real_probability is not None else None
        ),
        "fake_probability": (
            round(fake_probability, 2)
            if fake_probability is not None else None
        ),
        "frames_analyzed": len(frames),
        "media_type": "video",
        "explanation": (
            "Video-level prediction from sampled frames and the trained "
            "video classifier."
        ),
        "disclaimer": (
            "This frame-score baseline does not model temporal changes "
            "between frames and may misclassify videos."
        )
    }


# =========================================================
# MAIN MEDIA ROUTER
# =========================================================

def analyze_media(file_path):
    path = Path(file_path)

    image_extensions = {
        ".jpg", ".jpeg", ".png", ".webp", ".bmp"
    }
    audio_extensions = {
        ".wav", ".mp3", ".m4a", ".flac", ".ogg"
    }
    video_extensions = {
        ".mp4", ".avi", ".mov", ".mkv", ".webm"
    }

    if not path.exists():
        return {
            "status": "error",
            "error": "Uploaded file could not be found."
        }

    extension = path.suffix.lower()

    try:
        if extension in image_extensions:
            return analyze_image(path)

        if extension in audio_extensions:
            return analyze_audio(path)

        if extension in video_extensions:
            return analyze_video(path)

        return {
            "status": "error",
            "error": f"Unsupported file type: {extension}"
        }

    except Exception as error:
        print(
            f"DeepGuard X analysis error ({extension}):",
            repr(error)
        )

        return {
            "status": "error",
            "media_type": (
                "image" if extension in image_extensions else
                "audio" if extension in audio_extensions else
                "video" if extension in video_extensions else
                "unknown"
            ),
            "error": f"Analysis failed: {error}"
        }
